export type SubjectId = 'english' | 'urdu' | 'maths';

export type ActivityTypeId =
  // English activities
  | 'eng-letters'
  | 'eng-phonics'
  | 'eng-phonics-test'
  | 'eng-words'
  // Urdu activities
  | 'ur-letters'
  | 'ur-pictures'
  | 'ur-sounds'
  | 'ur-numbers'
  // Maths activities
  | 'math-count'
  | 'math-numbers'
  | 'math-addition';

export interface QuizOption {
  id: string;
  label?: string; // Text or letter
  subLabel?: string; // English phonics or romanization hint if useful
  illustration?: IllustrationId; // Rich interactive illustration
  customImageUrl?: string; // Custom uploaded image or local file path
  customAudioUrl?: string; // Custom voice recording or audio file path
  countVisual?: {
    itemId: IllustrationId;
    count: number;
  };
  isCorrect: boolean;
}

export interface QuizQuestion {
  id: string;
  subject: SubjectId;
  activityType: ActivityTypeId;
  // Spoken and prompt text
  prompt: string;
  promptUrdu?: string;
  speechText: string;
  speechLang: 'en' | 'ur';
  customAudioUrl?: string; // Parent/Teacher recorded voice prompt
  customImageUrl?: string; // Custom uploaded photo or local asset
  // Central visual presentation if any
  featuredIllustration?: IllustrationId;
  featuredLetter?: string;
  featuredNumber?: number;
  // For counting interactive game: count items that can be tapped individually
  countableItems?: {
    id: string;
    illustration: IllustrationId;
    name: string;
  }[];
  // For visual addition
  additionGroups?: {
    illustration: IllustrationId;
    count: number;
  }[];
  options: QuizOption[];
  hint: string;
  hintUrdu?: string;
}

